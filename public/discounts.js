/* Saee Plus: isolated 24-hour button; does not modify the details() function. */
(() => {
  'use strict';
  const PREFIX = 'saee-discount-used-v3:';
  const DAY = 24 * 60 * 60 * 1000;
  const $ = (s, root=document) => root.querySelector(s);
  function scope(){
    try {
      const raw = localStorage.getItem('sai-local-session-v1') || '';
      let email = raw;
      try { const parsed=JSON.parse(raw); email = parsed.email || parsed.user?.email || parsed.account?.email || raw; } catch(_) {}
      email=String(email||'').trim().toLowerCase();
      if(email && email!=='null' && email!=='{}') return 'user:'+email;
      let guest=localStorage.getItem('saee-discount-guest-id');
      if(!guest){guest='guest-'+Math.random().toString(36).slice(2)+Date.now().toString(36);localStorage.setItem('saee-discount-guest-id',guest)}
      return guest;
    } catch(_) { return 'browser'; }
  }
  function key(id){return PREFIX+encodeURIComponent(scope())+':'+encodeURIComponent(id)}
  function expiry(id){try{const n=Number(localStorage.getItem(key(id))||0);return n>Date.now()?n:0}catch(_){return 0}}
  function remaining(ms){const n=Math.max(0,Math.ceil(ms/1000));return `${Math.floor(n/3600)} ساعة و ${Math.floor((n%3600)/60)} دقيقة`}
  function notify(msg){let el=$('#saee-discount-toast');if(!el){el=document.createElement('div');el.id='saee-discount-toast';el.style.cssText='position:fixed;bottom:22px;left:50%;transform:translateX(-50%);z-index:999999;background:#075a52;color:white;padding:13px 18px;border-radius:12px;box-shadow:0 8px 28px #0003;max-width:90vw;text-align:center;font-weight:700';document.body.appendChild(el)}el.textContent=msg;el.hidden=false;clearTimeout(el._timer);el._timer=setTimeout(()=>el.hidden=true,3500)}
  function paint(btn){const id=btn.dataset.discountId;if(!id)return;let box=btn.parentElement;let timer=$('.saee-discount-timer',box);if(!timer){timer=document.createElement('small');timer.className='saee-discount-timer';timer.style.cssText='display:block;text-align:center;margin-top:8px;color:#788675';box.appendChild(timer)}const end=expiry(id);if(end){btn.disabled=true;btn.textContent='تم استخدام الخصم ✓';btn.style.opacity='.72';btn.style.cursor='not-allowed';timer.hidden=false;timer.textContent='يتفعّل بعد '+remaining(end-Date.now())}else{btn.disabled=false;btn.textContent='تم الخصم';btn.style.opacity='1';btn.style.cursor='pointer';timer.hidden=true;timer.textContent=''}}
  function ensure(){
    const dialog=$('#dialog-content'); if(!dialog)return;
    const kicker=$('.kicker',dialog); if(!kicker)return;
    const label=(kicker.textContent||'').replace(/\s+/g,' ').trim();
    if(!label.includes('التفاصيل') || !label.includes('خصومات سعي'))return;
    // Only add the button to a discount details dialog; leave other details untouched.
    if($('.saee-discount-use',dialog)) { paint($('.saee-discount-use',dialog)); return; }
    const id=window.__saeeLastDiscountId;
    // Obtain the ID from the favorite button's existing inline handler (generated by details()).
    const fav=[...dialog.querySelectorAll('button[onclick]')].find(b=>/saveFavorite\(/.test(b.getAttribute('onclick')||''));
    let found=id||'';
    if(!found && fav){const m=(fav.getAttribute('onclick')||'').match(/saveFavorite\('([^']+)'/);if(m)found=m[1]}
    if(!found)return;
    const wrap=document.createElement('div');wrap.className='saee-discount-details-use';wrap.style.cssText='margin:16px 0';
    const btn=document.createElement('button');btn.type='button';btn.className='button saee-discount-use';btn.dataset.discountId=found;btn.style.cssText='width:100%;justify-content:center';btn.textContent='تم الخصم';wrap.appendChild(btn);
    const price=dialog.querySelector('.price');
    const contact=[...dialog.querySelectorAll('p')].find(p=>(p.textContent||'').includes('بيانات تواصل'));
    (price||contact||dialog.lastElementChild)?.before(wrap);
    paint(btn);
  }
  document.addEventListener('click',e=>{const btn=e.target.closest('.saee-discount-use');if(!btn)return;e.preventDefault();e.stopPropagation();const id=(btn.dataset.discountId||'').trim();if(!id){notify('تعذر تحديد الخصم. أغلق التفاصيل وافتحها مجددًا.');return}const end=expiry(id);if(end){paint(btn);notify('هذا الخصم مستخدم بالفعل، ويتفعّل بعد '+remaining(end-Date.now()));return}try{localStorage.setItem(key(id),String(Date.now()+DAY));paint(btn);notify('تم تسجيل الخصم بنجاح. يمكنك استخدامه مرة أخرى بعد 24 ساعة.')}catch(_){notify('تعذر حفظ الاستخدام في هذا المتصفح.')}},true);
  const obs=new MutationObserver(ensure);
  function start(){ensure();const d=$('#dialog-content');if(d)obs.observe(d,{childList:true,subtree:true,characterData:true});setInterval(()=>{const b=$('.saee-discount-use');if(b)paint(b)},30000)}
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',start,{once:true});else start();
})();
